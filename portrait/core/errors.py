"""Исключения модуля «Портрет личности».

Все исключения модуля наследуются от PortraitError, поэтому интерфейс
может поймать любое из них одной строкой: except PortraitError.

Как модуль реагирует на каждую ситуацию — docs/errors.md.
"""


class PortraitError(Exception):
    """Базовое исключение модуля."""


class SourceError(PortraitError):
    """Источник вопросов недоступен или данные в нём повреждены.

    Например: нет папки с методиками, битый JSON, неизвестный method_id.
    Опрос в этом случае не запускается — показываем сообщение и выходим.
    """


class BlockError(PortraitError):
    """Методика нарушила контракт: не отдала вопросы или отдала неверные.

    Наружу из движка не выходит: движок ловит её, а методика
    получает в отчёте статус ERROR. Опрос при этом продолжается.
    """


class InvalidResultError(PortraitError):
    """Результат методики в неверном формате (проверяет сборщик).

    Наружу из сборщика не выходит: методика получает статус ERROR,
    а в отчёт записывается предупреждение.
    """


class SessionError(PortraitError):
    """Недопустимое действие в опросе.

    Например: ответ, когда вопросы уже закончились; переход вперёд
    без ответа; переход назад с первого вопроса; опрос без методик.
    """


class InvalidAnswerError(PortraitError):
    """Ответ не подходит к вопросу (например, варианта 7 у вопроса нет)."""
